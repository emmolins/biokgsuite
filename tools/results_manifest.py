#!/usr/bin/env python3
"""Generate results/MANIFEST.md from the files actually on disk.

The companion to tools/provenance.py: that one records where the INPUT data
came from, this one records what the notebooks PRODUCED from it. Between them,
every number in the manuscript traces to a dated file and a dated source.

    python tools/results_manifest.py

Regenerate after a run. Nothing here computes results; it only reports what is
present, so it cannot drift from the truth the way a hand-maintained list does.
"""
from __future__ import annotations

import datetime as _dt
import hashlib
import pickle
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / 'results'

# Directory name -> what the dimension measures. Unlisted notebooks still
# appear; this only adds a description.
DIMENSIONS = {
    '00_summary':           'Cross-dimension summary and rankings',
    '01_coverage':          'Entity and relation coverage vs. task-derived reference sets',
    '02_annotation_accuracy': 'Semantic validity of identifiers and annotations',
    '03_trustworthiness':   'Provenance, citation and curation signals',
    '04_topology':          'Graph structure and connectivity',
    '05_stability':         'Robustness of rankings to perturbation',
    '06_task_performance':  'Link prediction and multi-hop retrieval',
    '07_generalization':    'Transfer to sparse entities and unseen domains',
    'G01_benchmark':        'Grounding experiment: benchmark and selection audit',
    'G02_run':              'Grounding experiment: model runs',
    'G03_analysis':         'Grounding experiment: paired analysis and coverage control',
    'G04_scaling':          'Grounding experiment: capacity ladder',
    'G05_diagnostic':       'Grounding experiment: hard pairs',
}


def human(n: int) -> str:
    x = float(n)
    for u in ('B', 'KB', 'MB', 'GB'):
        if x < 1024 or u == 'GB':
            return f'{x:.0f}{u}' if u == 'B' else f'{x:.1f}{u}'
        x /= 1024


def sha16(p: Path) -> str:
    h = hashlib.sha256()
    with p.open('rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()[:16]


def mtime(p: Path) -> str:
    return _dt.datetime.utcfromtimestamp(p.stat().st_mtime).strftime('%Y-%m-%d %H:%M UTC')


def notebooks() -> list[str]:
    """Notebook output folders that actually contain something.

    An empty directory is scaffolding, not a result, and listing it as a
    notebook that produced nothing invites the reader to wonder what went wrong.
    """
    names = set()
    for sub in ('figures', 'tables'):
        d = RESULTS / sub
        if d.exists():
            names |= {p.name for p in d.iterdir()
                      if p.is_dir() and any(f.is_file() for f in p.iterdir())}
    ck = RESULTS / 'checkpoints'
    if ck.exists():
        names |= {p.stem for p in ck.glob('*.pkl')}
    return sorted(names)


def scores_from(ckpt: Path):
    """Headline scores, so the manifest shows what a run concluded."""
    try:
        with ckpt.open('rb') as fh:
            d = pickle.load(fh)
    except Exception as e:                                   # noqa: BLE001
        return None, f'unreadable ({e.__class__.__name__})'
    s = d.get('summary_scores')
    if not isinstance(s, dict) or not s:
        return None, None
    return s, d.get('reported_not_scored')


def main() -> int:
    if not RESULTS.exists():
        print(f'{RESULTS} does not exist; nothing to manifest.', file=sys.stderr)
        return 1

    now = _dt.datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')
    L = ['# Results manifest', '',
         f'Generated by `tools/results_manifest.py` at **{now}** from the files',
         'actually present under `results/`. Regenerate after any run.',
         '',
         'Input data versions are recorded separately in `data/PROVENANCE.md`.', '']

    nbs = notebooks()
    if not nbs:
        L += ['*No results yet. Run a notebook.*', '']

    for nb in nbs:
        desc = DIMENSIONS.get(nb, '')
        L += [f'## `{nb}`' + (f': {desc}' if desc else ''), '']

        ckpt = RESULTS / 'checkpoints' / f'{nb}.pkl'
        if ckpt.exists():
            scores, extra = scores_from(ckpt)
            if scores:
                L.append('| KG | ' + ' | '.join(scores) + ' |')
                L.append('|---|' + '---|' * len(scores))
                L.append('| **score** | '
                         + ' | '.join(f'{v:.4f}' if isinstance(v, float) else str(v)
                                      for v in scores.values()) + ' |')
                if isinstance(extra, list) and extra:
                    L.append('')
                    L.append('Computed and stored but **not scored**: '
                             + ', '.join(f'`{x}`' for x in extra) + '.')
            elif extra:
                L.append(f'Checkpoint {extra}.')
            L.append('')

        rows = []
        for kind, folder, pattern in (
                ('figure', RESULTS / 'figures' / nb, '*.pdf'),
                ('table', RESULTS / 'tables' / nb, '*.csv'),
                ('checkpoint', RESULTS / 'checkpoints', f'{nb}.pkl')):
            for p in sorted(folder.glob(pattern)) if folder.exists() else []:
                rows.append((kind, p))

        if rows:
            L += ['| Kind | File | Produced | Size | SHA-256 (16) |',
                  '|---|---|---|---|---|']
            for kind, p in rows:
                rel = p.relative_to(ROOT).as_posix()
                # A figure is one deliverable in two formats; list the PDF and
                # note the PNG beside it rather than duplicating every row.
                name = rel + (' (+ .png)' if kind == 'figure'
                              and p.with_suffix('.png').exists() else '')
                rows_size = p.stat().st_size
                L.append(f'| {kind} | `{name}` | {mtime(p)} | {human(rows_size)} '
                         f'| `{sha16(p)}` |')
            L.append('')
        else:
            L += ['*No files.*', '']

    # ---- display items: which output becomes which manuscript figure or table.
    # Declared in config/display_items.yaml, so a display item whose source file
    # is MISSING is reported here rather than discovered at submission.
    di_path = ROOT / 'config' / 'display_items.yaml'
    if di_path.exists():
        import yaml
        items = (yaml.safe_load(di_path.read_text()) or {}).get('display_items', {}) or {}
        L += ['---', '', '## Display items', '',
              'Declared in `config/display_items.yaml`. `MISSING` means the '
              'manuscript expects this output and the pipeline has not produced it.',
              '', '| Item | Source | Status | Caption |', '|---|---|---|---|']
        absent = 0
        for key, spec in items.items():
            srcs = [spec.get('source')] + list((spec.get('panels') or {}).values())
            rows = []
            for s in [x for x in srcs if x]:
                base = RESULTS / s
                ok = any(base.with_suffix(e).exists() for e in ('.pdf', '.png', '.csv'))
                rows.append((s, ok))
                absent += 0 if ok else 1
            status = 'OK' if all(ok for _, ok in rows) else '**MISSING**'
            L.append(f"| **{key}** | `{rows[0][0]}`"
                     + (f" (+{len(rows)-1} panels)" if len(rows) > 1 else '')
                     + f" | {status} | {spec.get('caption', '')} |")
        L += ['']
        if absent:
            L += [f'**{absent} declared display-item source(s) are missing.**', '']

    missing = [n for n in DIMENSIONS if n not in nbs]
    if missing:
        L += ['---', '', '**Not yet run:** '
              + ', '.join(f'`{n}`' for n in missing) + '.', '']

    out = RESULTS / 'MANIFEST.md'
    out.write_text('\n'.join(L))
    n_files = sum(1 for _ in RESULTS.rglob('*') if _.is_file()) - 1
    print(f'wrote {out.relative_to(ROOT)}  ({len(nbs)} notebooks, {n_files} files)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
