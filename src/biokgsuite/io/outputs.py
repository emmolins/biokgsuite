"""One place every notebook writes its results to.

    results/
      figures/<notebook>/<name>.pdf + .png     publication figures
      tables/<notebook>/<name>.csv             every table a notebook displays
      checkpoints/<notebook>.pkl               handoff to later notebooks
      MANIFEST.md                              generated by tools/results_manifest.py

The notebook name comes from the directory the notebook lives in, so the path
carries it and the file name does not have to: ``01_coverage/entity_coverage.pdf``
rather than ``01_coverage/01_entity_coverage.pdf``.

Why a helper rather than a few Path constants per notebook: tables were the gap.
Figures were being saved and tables only displayed, so a number that appears in
the supplement existed nowhere on disk and could not be regenerated without
rerunning the notebook and reading it off the screen. ``Outputs.table`` makes
saving a table as short as displaying one.
"""
from __future__ import annotations

import pickle
from pathlib import Path

import pandas as pd

from ..viz.style import save_fig


class Outputs:
    """Results writer for one notebook.

        out = Outputs('01_coverage', BASE)
        out.figure(fig, 'entity_coverage')      -> results/figures/01_coverage/entity_coverage.{pdf,png}
        out.table(entity_summary, 'entity_coverage')
        out.checkpoint(ckpt)                    -> results/checkpoints/01_coverage.pkl
    """

    def __init__(self, notebook: str, base, dpi: int = 600):
        self.notebook = notebook
        self.base = Path(base)
        self.dpi = dpi
        self.figures = self.base / 'results' / 'figures' / notebook
        self.tables = self.base / 'results' / 'tables' / notebook
        self.checkpoints = self.base / 'results' / 'checkpoints'
        self.written: list[Path] = []

    # ------------------------------------------------------------------ write
    def figure(self, fig, name: str) -> Path:
        """Save a figure as PDF (vector, the manuscript master) and PNG at
        ``dpi``; 600 meets the line-art floor of Nature-family and BiB artwork.
        """
        self.figures.mkdir(parents=True, exist_ok=True)
        save_fig(fig, self.figures, name, dpi=self.dpi)
        for ext in ('pdf', 'png'):
            self.written.append(self.figures / f'{name}.{ext}')
        return self.figures / f'{name}.pdf'

    def table(self, df: pd.DataFrame, name: str, index: bool = False) -> Path:
        """Save a table as CSV. Floats are written at full precision.

        Rounding belongs in the figure and in the manuscript, not in the file a
        reader recomputes from.
        """
        self.tables.mkdir(parents=True, exist_ok=True)
        path = self.tables / f'{name}.csv'
        df.to_csv(path, index=index)
        self.written.append(path)
        return path

    def checkpoint(self, obj) -> Path:
        """Pickle the scalar results later notebooks read."""
        self.checkpoints.mkdir(parents=True, exist_ok=True)
        path = self.checkpoints / f'{self.notebook}.pkl'
        with open(path, 'wb') as fh:
            pickle.dump(obj, fh)
        self.written.append(path)
        return path

    # ------------------------------------------------------------------- read
    def load_checkpoint(self, notebook: str | None = None):
        """Read another notebook's checkpoint, with a useful error if absent."""
        path = self.checkpoints / f'{notebook or self.notebook}.pkl'
        if not path.exists():
            raise FileNotFoundError(
                f'{path} missing. Run biokgsuite_dimensions/{notebook or self.notebook} first.')
        with open(path, 'rb') as fh:
            return pickle.load(fh)

    # ------------------------------------------------------------------ report
    def summary(self) -> str:
        rel = sorted({p.relative_to(self.base).as_posix() for p in self.written})
        return (f'{self.notebook}: wrote {len(rel)} files\n  '
                + '\n  '.join(rel)) if rel else f'{self.notebook}: nothing written'
